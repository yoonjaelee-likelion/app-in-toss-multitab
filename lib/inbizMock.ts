type Kind = "food" | "retail" | "app" | "service";

function kindOf(idea: string): Kind {
  const s = idea.toLowerCase();
  if (/식당|레스토랑|카페|타코|치킨|피자|분식|음식|베이커리|주점|푸드|맛집|배달/.test(s)) {
    return "food";
  }
  if (/앱|플랫폼|서비스|saas|ai|웹|소프트웨어|구독/.test(s)) return "app";
  if (/쇼핑몰|판매|스토어|매장|편의점|리테일|브랜드|제품/.test(s)) return "retail";
  return "service";
}

