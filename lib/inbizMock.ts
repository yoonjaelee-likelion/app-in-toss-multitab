export function mockInbiz(req: InbizRequest, slot: string): string {
  if (req.op === "staff") {
    const k = kindOf(req.idea);
    const conf = STAFF[k];
    const lines = [`정의: ${conf.headline(req.idea)}`];
    for (const [key, why] of conf.picks) lines.push(`부서: ${key} | ${why}`);
    return lines.join("\n");
  }
  if (req.op === "meet") {
    const names = new Set((req.reports ?? []).map((r) => r.name));
    const hit = MEETINGS.filter((m) => {
      const [a, b] = m.replace(/^회의\s*[:：]\s*/, "").split("|");
      return names.has(a.trim()) && names.has(b.trim());
    });
    return (hit.length ? hit : MEETINGS.slice(0, 2)).join("\n");
  }
  if (req.op === "diagnose") return DIAGNOSIS;
  return REPORT[slot] ?? REPORT.market;
}

