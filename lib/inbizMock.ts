export function mockInbiz(req: InbizRequest, slot: string): string {
  const profile = PROFILES[kindOf(req.idea)];

  if (req.op === "staff") {
    const lines = [`정의: ${profile.headline(req.idea)}`];
    for (const [key, why] of profile.picks) lines.push(`부서: ${key} | ${why}`);
    return lines.join("\n");
  }

  if (req.op === "meet") {
    const names = new Set((req.reports ?? []).map((r) => r.name));
    const hit = profile.meetings.filter((m) => {
      const [a, b] = m.replace(/^회의\s*[:：]\s*/, "").split("|");
      return names.has(a.trim()) && names.has(b.trim());
    });
    return (hit.length ? hit : profile.meetings.slice(0, 2)).join("\n");
  }

  if (req.op === "diagnose") return profile.diagnosis;

  return (
    profile.reports[slot] ??
    `발견: 이 영역에서는 아직 판단할 자료가 부족하다.

- 「${clip(req.idea, 22)}」에 대해 이 부서가 볼 수 있는 공개 자료가 얕다
- 가정을 세우기 전에 실측이 필요한 구간이다

우려: 자료 없이 숫자를 만들면 나머지 부서 계산까지 같이 틀어진다.`
  );
}

