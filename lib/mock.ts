export function mockText(req: AskRequest, slot: string): string {
  const red = req.stance === "redteam";

  if (req.mode === "synthesis") {
    return red ? RED_SYNTH : synthesisText(participants(req));
  }
  if (req.mode === "debate") {
    const other = req.targets.find((s) => s !== slot);
    const name = other ? (MODEL_BY_ID[other]?.name ?? other) : "다른 AI";
    const table = red ? RED_DEBATE : DEBATE;
    return (table[slot] ?? table.sonnet)(name);
  }
  const table = red ? RED_ASK : ASK;
  return (table[slot] ?? table.sonnet)(req.question);
}

