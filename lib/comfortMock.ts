/* ── 조립 ─────────────────────────────────────────────────── */

export function mockComfort(req: ComfortRequest): string {
  const story = req.record.map((r) => r.text).join(" ");
  const kind = kindOf(story);
  const adult = req.rating === "adult";

  if (req.first) return (adult ? FIRST_ADULT : FIRST)[kind][req.friend];

  const pool = (adult ? FOLLOW_ADULT : FOLLOW)[req.friend];
  // 같은 방에서 같은 말이 두 번 나오지 않게, 지금까지 나온 말을 피해서 고른다
  const said = new Set(req.record.map((r) => r.text.trim()));
  const fresh = pool.filter((p) => !said.has(p));
  const list = fresh.length ? fresh : pool;
  return list[Math.floor(Math.random() * list.length)];
}

