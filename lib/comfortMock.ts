type Kind = "love" | "work" | "family" | "friend" | "study" | "generic";

const SIGNALS: Record<Exclude<Kind, "generic">, RegExp> = {
  love: /남친|여친|남자친구|여자친구|애인|썸|연애|헤어|이별|결혼|고백|바람|데이트/,
  work: /회사|팀장|상사|부장|직장|출근|퇴사|야근|업무|프로젝트|월급|동료|사장/,
  family: /엄마|아빠|부모|가족|형|누나|언니|오빠|동생|시댁|처가|친정/,
  friend: /친구|지인|모임|단톡|축의금|절교|무리|동창/,
  study: /시험|공부|학교|과제|교수|학점|취준|면접|졸업|수능/,
};

function kindOf(text: string): Kind {
  let best: Kind = "generic";
  let top = 0;
  for (const [kind, re] of Object.entries(SIGNALS) as [Kind, RegExp][]) {
    const hits = (text.match(new RegExp(re.source, "g")) ?? []).length;
    if (hits > top) {
      top = hits;
      best = kind;
    }
  }
  return best;
}

