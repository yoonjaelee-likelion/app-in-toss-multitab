export function mockCourt(req: CourtRequest): string {
  const c = req.caseFile;
  const kind = kindOf(`${c.man.claim} ${c.woman.claim}`);
  const table: Record<Rating, Record<Kind, Script>> = { normal: NORMAL, adult: ADULT };
  const s = table[c.rating][kind];

  // 지금 말하는 쪽의 상대 모델 — 이름을 대고 까는 데 쓴다
  const me = req.speaker === "b" ? "b" : "a";
  const rival = me === "a" ? req.cast.b : req.cast.a;

  const fill = (t: string) =>
    t
      .replaceAll("{M}", nameOf(c.man, "남자"))
      .replaceAll("{W}", nameOf(c.woman, "여자"))
      .replaceAll("{OA}", shortOf(rival))
      .replaceAll("{OM}", makerOf(rival));

  switch (req.op) {
    case "open":
      return fill(s.open);
    case "callWoman":
      return fill(s.callWoman);
    case "wrap":
      return fill(s.wrap);
    case "jury":
      return fill(s.jury);
    case "verdict":
      return fill(s.verdict);
    default: {
      // 라운드가 대본보다 많아지면 마지막 라운드를 다시 쓴다
      const round = Math.min(Math.max(req.round ?? 1, 1), 3) as 1 | 2 | 3;
      const line = me === "a" ? ([s.a1, s.a2, s.a3] as const) : ([s.b1, s.b2, s.b3] as const);
      return fill(line[round - 1]);
    }
  }
}

